func docFiles(a *API) map[string][]byte {
	files := map[string][]byte{
		filepath.Join("docs", "api.md"):           []byte(a.APIDoc()),
		filepath.Join("docs", "pack-format.md"):   []byte(packFormatDoc()),
		filepath.Join("docs", "pack.schema.json"): packSchema(),
	}
	// Claude Code reads skills from .claude/skills, Codex and others from
	// .agents/skills: keep a copy (symlinks break on Windows checkouts).
	skills, _ := filepath.Glob(filepath.Join(".agents", "skills", "*", "SKILL.md"))
	for _, s := range skills {
		if raw, err := os.ReadFile(s); err == nil {
			files[filepath.Join(".claude", strings.TrimPrefix(s, ".agents"+string(filepath.Separator)))] = raw
		}
	}
	return files
}

func docs(check bool) int {
	files := docFiles(&API{lab: &Lab{}})
	names := make([]string, 0, len(files))
	for n := range files {
		names = append(names, n)
	}
	sort.Strings(names)
	stale := 0
	for _, n := range names {
		old, _ := os.ReadFile(n)
		if string(old) == string(files[n]) {
			continue
		}
		if check {
			fmt.Println("stale:", n, "— run: ./fire docs")
			stale++
			continue
		}
		_ = os.MkdirAll(filepath.Dir(n), 0o755)
		if err := os.WriteFile(n, files[n], 0o644); err != nil {
			fmt.Println(err)
			return 1
		}
		fmt.Println("wrote", n)
	}
	if stale > 0 {
		return 1
	}
	return 0
}
