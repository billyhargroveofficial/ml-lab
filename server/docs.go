func schemaOf(t reflect.Type, defs map[string]any) map[string]any {
	switch t.Kind() {
	case reflect.String:
		return map[string]any{"type": "string"}
	case reflect.Int:
		return map[string]any{"type": "integer"}
	case reflect.Float64:
		return map[string]any{"type": "number"}
	case reflect.Bool:
		return map[string]any{"type": "boolean"}
	case reflect.Slice:
		return map[string]any{"type": "array", "items": schemaOf(t.Elem(), defs)}
	case reflect.Struct:
		name := t.Name()
		if _, ok := defs[name]; !ok {
			defs[name] = nil
			props := map[string]any{}
			req := []string{}
			for i := 0; i < t.NumField(); i++ {
				f := t.Field(i)
				tag := strings.Split(f.Tag.Get("json"), ",")
				if tag[0] == "" || tag[0] == "-" {
					continue
				}
				s := schemaOf(f.Type, defs)
				s["description"] = fieldNotes[name+"."+tag[0]]
				props[tag[0]] = s
				if len(tag) == 1 {
					req = append(req, tag[0])
				}
			}
			defs[name] = map[string]any{"type": "object", "additionalProperties": false, "properties": props, "required": req}
		}
		return map[string]any{"$ref": "#/$defs/" + name}
	}
	panic("schema: unsupported " + t.String())
}

func packSchema() []byte {
	defs := map[string]any{}
	root := schemaOf(reflect.TypeOf(PackFile{}), defs)
	out := map[string]any{"$schema": "https://json-schema.org/draft/2020-12/schema", "title": "FIRe pack (" + PackFormat + ")", "$ref": root["$ref"], "$defs": defs}
	b, _ := json.MarshalIndent(out, "", "  ")
	return append(b, '\n')
}

func packFormatDoc() string {
	var b strings.Builder
	b.WriteString("# Pack format\n\n" + generated + "\n\n")
	b.WriteString("A pack is a folder `packs/<id>/` with `pack.json` (format `" + PackFormat + "`) and, optionally, lesson files. The app reloads packs within a few seconds of a change. JSON Schema: [`pack.schema.json`](pack.schema.json). A complete small example: [`examples/packs/softmax`](../examples/packs/softmax/pack.json).\n\nStructure: optional **categories** (big groups, display only) → **topics** → **ideas** (one lesson each, with its questions). A small pack can skip categories.\n\n")
	for _, t := range []reflect.Type{reflect.TypeOf(PackFile{}), reflect.TypeOf(PackCategory{}), reflect.TypeOf(PackTopic{}), reflect.TypeOf(PackIdea{}), reflect.TypeOf(PackLink{}), reflect.TypeOf(Question{})} {
		fmt.Fprintf(&b, "## %s\n\n| Field | Type | Required | Meaning |\n|---|---|---|---|\n", t.Name())
		for i := 0; i < t.NumField(); i++ {
			f := t.Field(i)
			tag := strings.Split(f.Tag.Get("json"), ",")
			req := "yes"
			if len(tag) > 1 {
				req = "no"
			}
			typ := strings.TrimPrefix(f.Type.String(), "main.")
			typ = strings.ReplaceAll(typ, "main.", "")
			fmt.Fprintf(&b, "| `%s` | %s | %s | %s |\n", tag[0], typ, req, strings.ReplaceAll(fieldNotes[t.Name()+"."+tag[0]], "|", "\\|"))
		}
		b.WriteString("\n")
	}
	b.WriteString(weightRubric)
	b.WriteString("\n## What `fire validate` checks\n\n")
	for _, c := range validateChecks {
		b.WriteString("- " + c + "\n")
	}
	return b.String()
}

